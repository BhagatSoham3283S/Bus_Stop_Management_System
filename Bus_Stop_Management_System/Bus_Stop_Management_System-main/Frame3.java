    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        try{
            Connection con=DBConnection.getConnection();
            String sql="SELECT * FROM bus_management WHERE bus_id=?";
            PreparedStatement pst=con.prepareStatement(sql);
            pst.setInt(1,Integer.parseInt(jTextField1.getText()));
            ResultSet rs = pst.executeQuery();
            if(rs.next()){
                jTextField2.setText(rs.getString("bus_number"));
                jTextField3.setText(rs.getString("driver_name"));
                jTextField4.setText(rs.getString("capacity"));
                cmbStatus.setSelectedItem(rs.getString("status"));
            }
            else{
                JOptionPane.showMessageDialog(this,"Record Not Found");
            }
        }
        catch(HeadlessException | NumberFormatException | SQLException e){
            JOptionPane.showMessageDialog(this,e);
        }

    }//GEN-LAST:event_jButton7ActionPerformed


    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String username = jTextField5.getText().trim();
        String password = new String(jPasswordField1.getPassword());
        
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Username and Password.");
            return;
        }
        
        try{
            Connection mycon = DBConnection.getConnection();
            PreparedStatement check;
            check = mycon.prepareStatement("SELECT * FROM admin_login WHERE username=?");
            check.setString(1,username);
            ResultSet rs = check.executeQuery();
            
            if(rs.next()){
                JOptionPane.showMessageDialog(this, "Admin Already Exists");
            }
            else{
                PreparedStatement pst;
                pst = mycon.prepareStatement("INSERT INTO admin_login(username,password) VALUES(?,?)");
                pst.setString(1,username);
                pst.setString(2,password);
                pst.executeUpdate();
                pst.close();
                
                JOptionPane.showMessageDialog(this, "Admin Regstered Successfully!");
                jTextField5.setText("");
                jPasswordField1.setText("");
            }
            rs.close();
            check.close();
            mycon.close();
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(this,e);
        }
    }//GEN-LAST:event_jButton3ActionPerformed


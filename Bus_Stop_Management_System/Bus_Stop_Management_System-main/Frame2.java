    private void loadDashboardData() {
        try {
            Connection con = DBConnection.getConnection();

            String sql1 = "SELECT COUNT(*) FROM bus_management";
            PreparedStatement pst1 = con.prepareStatement(sql1);
            ResultSet rs1 = pst1.executeQuery();

            if (rs1.next()) {
                jTextField1.setText(rs1.getString(1));
            }

            String sql2 = "SELECT COUNT(*) FROM bus_stop";
            PreparedStatement pst2 = con.prepareStatement(sql2);
            ResultSet rs2 = pst2.executeQuery();

            if (rs2.next()) {
                jTextField2.setText(rs2.getString(1));
            }

            String sql3 = "SELECT COUNT(*) FROM bus_route";
            PreparedStatement pst3 = con.prepareStatement(sql3);
            ResultSet rs3 = pst3.executeQuery();

            if (rs3.next()) {
                jTextField3.setText(rs3.getString(1));
            }

            String sql4 = "SELECT COUNT(*) FROM bus_schedule";
            PreparedStatement pst4 = con.prepareStatement(sql4);
            ResultSet rs4 = pst4.executeQuery();

            if (rs4.next()) {
                jTextField4.setText(rs4.getString(1));
            }
        }
        catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
    }
    

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
            Connection con = DBConnection.getConnection();
            String sql = "UPDATE buS_route SET source=?, destination=?, distance=? WHERE route_id=?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, jTextField2.getText());
            pst.setString(2, jTextField3.getText());
            pst.setInt(3, Integer.parseInt(jTextField4.getText()));
            pst.setInt(4, Integer.parseInt(jTextField1.getText()));
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this,"Route Updated Successfully");
            loadTable();
        }
        catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Route ID and Distance must be numbers.");
        }
        catch (SQLException e) {
            JOptionPane.showMessageDialog(this,"Database Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton3ActionPerformed

